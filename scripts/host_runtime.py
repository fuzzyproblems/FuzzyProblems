"""Host routing and bounded, identity-free diagnostics. No AI/auth/network calls."""
import argparse
import copy
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
HOSTS = ('codex', 'claude')
CLAUDE_MINIMUM = (2, 1, 251)
# Syntax accepted by Claude's worker frontmatter; the chosen model may support
# fewer levels. No translation from Codex levels and no model tier allowlist.
CLAUDE_EFFORTS = {'inherit', 'low', 'medium', 'high', 'xhigh', 'max'}
DEFAULTS = {
    'codex': {'model': 'gpt-6-sol', 'reasoning_effort': 'medium'},
    'claude': {'model': 'inherit', 'reasoning_effort': 'inherit'},
}
CLAUDE_ENV = {'CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC': '1',
              'CLAUDE_CODE_ENABLE_TELEMETRY': '0',
              'CLAUDE_CODE_DISABLE_OFFICIAL_MARKETPLACE_AUTOINSTALL': '1'}
LOCAL_DELIVERY = '.claude/agents/fuzzy-delivery-local.md'
LOCAL_MARKER = '<!-- Generated by host_runtime; recipient configuration, do not distribute. -->'


def safe(root, relative):
    root = Path(root).resolve()
    path = root / relative
    if not path.is_relative_to(root) or '..' in path.parts:
        raise ValueError('Project path must stay inside the project.')
    for item in [path, *path.parents]:
        if item.is_symlink() or item.is_junction():
            raise ValueError('Expected a regular project path; symlinks/junctions are not supported here.')
        if item == root:
            break
    return path


def write_json(path, value):
    """Atomic local update; never partially replace recipient configuration."""
    data = json.dumps(value, ensure_ascii=False, indent=2) + '\n'
    atomic_text(path, data)


def atomic_text(path, data):
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', newline='\n',
                                     prefix='.host-', dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(data)
            stream.close()
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def load(root=ROOT):
    path = safe(root, 'pipeline-config.json')
    if not path.exists():
        path = safe(root, 'pipeline-config.example.json')
    try:
        value = json.loads(path.read_text(encoding='utf-8')) if path.exists() else {}
    except (OSError, ValueError):
        raise ValueError('Cannot read pipeline-config.json as a regular JSON configuration.') from None
    if not isinstance(value, dict):
        raise ValueError('pipeline-config.json must contain an object.')
    return value


def configuration(root=ROOT, host=None, value=None):
    value = load(root) if value is None else value
    selected = host or value.get('host', 'codex')
    if selected not in HOSTS:
        raise ValueError('Select host codex or claude with init --host HOST.')
    hosts = value.get('hosts', {})
    if not isinstance(hosts, dict) or any(key not in HOSTS for key in hosts):
        raise ValueError('hosts must be an object keyed by codex and/or claude.')
    settings = hosts.get(selected, {})
    if not isinstance(settings, dict):
        raise ValueError('Each host configuration must be an object.')
    delivery = settings.get('delivery')
    if delivery is None:
        # The original unscoped delivery setting has always meant Codex.
        # Selecting Claude must never apply that OpenAI model to Claude.
        delivery = value.get('delivery', DEFAULTS[selected]) if selected == 'codex' else DEFAULTS[selected]
    if not isinstance(delivery, dict):
        raise ValueError('delivery must contain model and reasoning_effort.')
    for key in ('model', 'reasoning_effort'):
        setting = delivery.get(key)
        if (not isinstance(setting, str) or not setting.strip() or setting != setting.strip()
                or len(setting) > 256 or any(c.isspace() for c in setting)):
            raise ValueError('Delivery model and reasoning_effort must be nonempty single tokens; use inherit for session selection.')
    if selected == 'claude' and delivery['reasoning_effort'] not in CLAUDE_EFFORTS:
        raise ValueError('Unsupported Claude effort syntax. Use inherit, low, medium, high, xhigh or max; confirm model support in Claude. Codex effort labels are not translated.')
    return selected, {key: delivery[key] for key in ('model', 'reasoning_effort')}


def select(root=ROOT, host=None):
    """Preserve all existing fields and bytes unless an explicit host changes."""
    value = load(root)
    configuration(root, host, value)
    path = safe(root, 'pipeline-config.json')
    if host and value.get('host') != host:
        value = copy.deepcopy(value)
        value['host'] = host
        write_json(path, value)
    elif not path.exists():
        write_json(path, value)


def require_codex(root=ROOT, host=None):
    selected, _ = configuration(root, host)
    if selected != 'codex':
        raise ValueError('This optional CLI review/detached queue command is Codex-only. In Claude Code use /job-queue and its native independent workers; no Codex installation is needed. To explicitly use the Codex fallback, select --host codex and configure your own Codex CLI access.')


def sync_claude_delivery(root, delivery):
    """Materialize an explicit effort override in Claude's supported native field.

    The inherited route needs no generated file. Never overwrite a hand-written
    worker; generated recipient configuration is excluded from release allowlists.
    """
    if delivery == DEFAULTS['claude']:
        return 'fuzzy-delivery'
    target = safe(root, LOCAL_DELIVERY)
    if target.exists() and LOCAL_MARKER not in target.read_text(encoding='utf-8'):
        raise ValueError('Local delivery worker already exists and is not generator-owned; preserve it and choose another configuration.')
    template = safe(root, '.claude/agents/fuzzy-delivery.md').read_text(encoding='utf-8')
    _, frontmatter, body = template.split('---', 2)
    fields = [line for line in frontmatter.strip().splitlines()
              if not line.startswith(('name:', 'model:', 'effort:'))]
    fields.insert(0, 'name: fuzzy-delivery-local')
    fields.append('model: ' + json.dumps(delivery['model']))
    if delivery['reasoning_effort'] != 'inherit':
        fields.append('effort: ' + delivery['reasoning_effort'])
    atomic_text(target, '---\n' + '\n'.join(fields) + '\n---\n' + LOCAL_MARKER + '\n' + body.lstrip())
    return 'fuzzy-delivery-local'


def describe(root=ROOT, host=None, cli=None, probe=True, sync_delivery=False):
    selected, delivery = configuration(root, host)
    prefix = '.claude' if selected == 'claude' else '.codex'
    instruction = 'CLAUDE.md' if selected == 'claude' else 'AGENTS.md'
    skill_root = '.claude/skills' if selected == 'claude' else '.agents/skills'
    roles = [f'{prefix}/agents/fuzzy-{r}.md' if selected == 'claude' else f'{prefix}/agents/{r}.toml'
             for r in ('author', 'reviewer', 'delivery')]
    files = [instruction, f'{skill_root}/fuzzy-start/SKILL.md', f'{skill_root}/job-queue/SKILL.md', *roles]
    missing = [name for name in files if not safe(root, name).is_file()]
    executable = cli or shutil.which(selected)
    report = {'host': selected, 'delivery': delivery, 'adapter_files_present': not missing,
              'missing_adapter_files': missing, 'cli_available': bool(executable),
              'authentication': 'not_checked', 'model_support': 'confirm_in_host',
              'native_worker_execution': 'not_checked', 'external_ai_processing': True,
              'optional_cli_queue_and_review': 'codex_only',
              'status': 'cli_not_probed' if executable else 'cli_missing',
              'next': 'Open this project in the selected host, select an available model/effort and use its fuzzy-start skill. Authentication is separate from Python initialization.'}
    if not executable:
        report['next'] = ('Install or locate Claude Code, open this project and use /fuzzy-start. Python readiness is independent of AI authentication.'
                          if selected == 'claude' else
                          'Open this project in a Codex host with native workers. Install/locate the public Codex CLI only for optional CLI commands; authentication is separate.')
    if selected == 'claude':
        report['minimum_cli_version'] = '.'.join(map(str, CLAUDE_MINIMUM))
        report['delivery_agent'] = ('fuzzy-delivery' if delivery == DEFAULTS['claude'] else 'fuzzy-delivery-local')
        if sync_delivery:
            report['delivery_agent'] = sync_claude_delivery(root, delivery)
    if executable and probe:
        try:
            # Never dump raw help, executable paths, credentials, account status,
            # environment or error text into potentially shared diagnostics.
            result = subprocess.run([executable, '--version'], capture_output=True,
                                    text=True, encoding='utf-8', errors='replace', timeout=10,
                                    cwd=root, env=dict(os.environ, **(CLAUDE_ENV if selected == 'claude' else {})))
            match = re.search(r'\b(\d+)\.(\d+)\.(\d+)(?:[-.][A-Za-z0-9.]+)?', result.stdout)
            if result.returncode or not match:
                report['status'] = 'cli_probe_failed'
            else:
                report['cli_version'] = match.group(0)
                report['status'] = 'cli_detected_auth_not_checked'
                if selected == 'claude' and tuple(map(int, match.group(1, 2, 3))) < CLAUDE_MINIMUM:
                    report['status'] = 'cli_upgrade_required'
                    report['next'] = 'Update Claude Code through its supported installer, then reopen this project. The adapter requires current model inheritance behavior.'
        except (OSError, subprocess.TimeoutExpired):
            report['status'] = 'cli_probe_failed'
        if report['status'] == 'cli_probe_failed':
            report['next'] = 'Check the selected CLI executable and normal host permissions; --no-probe inspects only project files and configuration.'
    if missing:
        report['status'] = 'adapter_files_missing'
        report['next'] = 'Re-extract the complete distribution including hidden directories.'
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host', choices=HOSTS)
    parser.add_argument('--cli', help='Executable for this diagnostic only; never stored')
    parser.add_argument('--no-probe', action='store_true', help='Inspect files/configuration without starting a CLI')
    parser.add_argument('--sync-delivery', action='store_true', help='Generate the local Claude delivery override from recipient configuration')
    args = parser.parse_args(argv)
    try:
        report = describe(host=args.host, cli=args.cli, probe=not args.no_probe, sync_delivery=args.sync_delivery)
    except ValueError as error:
        parser.exit(2, str(error) + '\n')
    except OSError:
        parser.exit(2, 'Cannot inspect or update the local host adapter; check regular project files and permissions.\n')
    print(json.dumps(report, ensure_ascii=False, indent=2))
    return 1 if report['status'] in {'cli_probe_failed', 'cli_upgrade_required', 'adapter_files_missing'} else 0


if __name__ == '__main__':
    raise SystemExit(main())
