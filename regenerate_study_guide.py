def navigation_page(node, root):
    return root/NAVIGATION if node.path==root/'output' else node.path/GROUP_NAVIGATION

def breadcrumbs(node, root, page):
    if node.path==root/'output':return ''
    e=html.escape
    parts=node.path.relative_to(root/'output').parts
    links=['<a href="'+e(href(page,root/NAVIGATION))+'">Main guide</a>']
    ancestor=root/'output'
    for part in parts[:-1]:
        ancestor=ancestor/part
        links.append('<a href="'+e(href(page,ancestor/GROUP_NAVIGATION))+'">'+e(part)+'</a>')
    links.append('<span aria-current="page">'+e(parts[-1])+'</span>')
    parent=root/NAVIGATION if len(parts)==1 else node.path.parent/GROUP_NAVIGATION
    label='Main guide' if len(parts)==1 else 'Parent group'
    return '<nav class="breadcrumbs" aria-label="Breadcrumb">'+ ' <span aria-hidden="true">›</span> '.join(links)+'</nav><p class="parent"><a href="'+e(href(page,parent))+'">← '+label+'</a></p>'

def document(node, root):
    page=navigation_page(node,root)
    groups={}
    if node.guide:groups[('',node.guide['group'])]=[dict(node.guide,action='Open this guide →')]
    for child in node.children:
        if child.children:
            row={'folder':child.path.name,'lesson':child.path.name,'scope':'Group','version':1,
                 'title':'Browse the study guides in this group.','target':child.path/GROUP_NAVIGATION,
                 'action':'Open group →'}
            groups[(name_key(child.path.name),'group')]=[row]
        else:
            row=dict(child.guide,action='Open study guide →')
            groups.setdefault((row['group'],'guide'),[]).append(row)
    body=''
    for group in sorted(groups,key=lambda group:tuple(natural_key(part) for part in group)):
        versions=sorted(groups[group],key=lambda r:(r['version'],r['folder']),reverse=True)
        r=versions[0];e=html.escape
        body+='<article><p class="scope">'+e(r['scope'])+(' · v'+str(r['version']) if r['version']>1 else '')+'</p><h2>'+e(r['lesson'])+'</h2><p class="topic">'+e(r['title'])+'</p><a class="open" href="'+e(href(page,r['target']))+'">'+r['action']+'</a>'
        if len(versions)>1:
            body+='<details><summary>Earlier versions</summary><ul>'+''.join('<li><a href="'+e(href(page,old['target']))+'">'+e(old['lesson'] if old['target'].name!='index.html' else old['scope'])+' · v'+str(old['version'])+'</a></li>' for old in versions[1:])+'</ul></details>'
        body+='</article>'
    if not body:body='<p>No study guides are available yet.</p>'
    title='Study guides' if node.path==root/'output' else node.path.name
    return HEADER+'<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>'+html.escape(title)+'</title><style>'+CSS+'</style></head><body><main><p class="eyebrow">Learning library</p>'+breadcrumbs(node,root,page)+'<h1>'+html.escape(title)+'</h1><p class="intro">Choose a lesson or objective to begin.</p><div class="grid">'+body+'</div></main></body></html>\n'

def check_destination(dest, root):
    safe_path(dest,root)
    exact_name(dest.parent,dest.name)
    if dest.exists() and not owned(dest):
        raise ValueError('Refusing to overwrite an unowned navigation page: '+str(dest))

def write_page(dest, text, root):
    check_destination(dest,root)
    if not dest.exists() or dest.read_bytes()!=text.encode('utf-8'):
        temporary=None
        try:
            with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',newline='\n',
                                             dir=dest.parent,prefix='.study-guide-',suffix='.tmp',delete=False) as stream:
                temporary=Path(stream.name)
                stream.write(text)
            os.utime(temporary,(315532800,315532800))
            temporary.replace(dest)
        finally:
            if temporary is not None:temporary.unlink(missing_ok=True)

def _refresh(root, log):
    output=root/'output'
    safe_path(output,root);exact_name(root,'output')
    if output.exists() and not output.is_dir():raise ValueError('output must be a directory')
    tree,nodes,generated=discover(output,log)
    pages={navigation_page(node,root):document(node,root)
           for node in nodes if node is tree or node.children}
    # Preflight every target before changing any catalogue. Preserve old pages on scan failure.
    for dest in pages:check_destination(dest,root)
    output.mkdir(exist_ok=True)
    # Descendants first, main guide last; links never point to not-yet-written new pages.
    for dest in sorted(pages,key=lambda p:(-len(p.parts),p.as_posix())):
        write_page(dest,pages[dest],root)
    for stale in sorted(generated-set(pages)):
        safe_path(stale,root)
        if owned(stale):
            stale.unlink();log.append(repr(stale.relative_to(root).as_posix())+': removed stale navigation page')
    guides=[node for node in nodes if node.guide]
    main=root/NAVIGATION
    return {'catalogue':NAVIGATION,
            'lesson_or_objective_groups':len({(node.path.parent,node.guide['group']) for node in guides}),
            'versions':len(guides),'links':sorted(href(main,node.guide['target']) for node in guides),
            'navigation_pages':sorted(href(main,dest) for dest in pages)}

def failure_summary(error,stage):
    """Describe failures without serializing paths, messages or traceback frames."""
    category=('text_encoding' if isinstance(error,UnicodeError) else
              'filesystem' if isinstance(error,OSError) else
              'navigation_validation' if isinstance(error,ValueError) else 'unexpected')
    fields={'stage':stage,'category':category,'exception':type(error).__name__}
    if isinstance(getattr(error,'errno',None),int):fields['errno']=error.errno
    return json.dumps(fields,sort_keys=True)


def write_diagnostics(output,root,log):
    destination=output/'diagnostics.txt'
    safe_path(destination,root);exact_name(output,destination.name)
    if destination.exists() and not destination.is_file():
        raise ValueError('Diagnostics destination must be a regular file')
    temporary=None
    try:
        with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',newline='\n',dir=output,
                                         prefix='.study-guide-',suffix='.tmp',delete=False) as stream:
            temporary=Path(stream.name)
            stream.write('\n'.join(log)+'\n')
        os.utime(temporary,(315532800,315532800))
        temporary.replace(destination)
    finally:
        if temporary is not None:temporary.unlink(missing_ok=True)


def refresh(root=ROOT):
    root=Path(root).absolute();output=root/'output'
    log=['Study guide regeneration diagnostics',
         'UTC: '+datetime.now(timezone.utc).isoformat(),
         'Python: '+'.'.join(map(str,sys.version_info[:3])),
         'OS: '+platform.system(),
         'Script: regenerate_study_guide.py',
         'Scan directory: output/ (relative to the script)',
         'Discover exact regular index.html files recursively; exclude hidden/supporting folders, symlinks and junctions.',
         'Supporting folder names: '+', '.join(sorted(SUPPORT_FOLDERS)),
         '', 'Discovery decisions:']
    try:
        result=_refresh(root,log)
        log.extend(['','SUCCESS: '+str(result['versions'])+' study guide(s) detected.',
                    'Catalogue: '+NAVIGATION])
        if not result['versions']:
            log.append('Check for unextracted ZIP files, missing/download-incomplete guides, filename case (index.html), excluded support names or aliases/symlinks. Place the script beside the intended output/ folder.')
        return result
    except Exception as exc:
        log.extend(['','FAILED: '+failure_summary(exc,'regeneration')])
        raise
    finally:
        try:
            write_diagnostics(output,root,log)
        except (OSError,ValueError) as exc:
            print('Could not write diagnostics.txt: '+failure_summary(exc,'diagnostics_write'),file=sys.stderr)

def main():
    try:
        print(json.dumps(refresh()))
        return 0
    except Exception as exc:
        print('Catalogue refresh failed: '+failure_summary(exc,'regeneration'),file=sys.stderr)
        return 1


if __name__=='__main__':sys.exit(main())
