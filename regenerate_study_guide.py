"""Regenerate root StudyGuide.html and grouping navigation.html pages in output/.

Run with Python from any working directory. Only the standard library is needed;
copy this script alongside output/ to use it without the project tooling.
Study files are read, never moved or rewritten. Diagnostics stay in output/.
"""
