ROOT=Path(__file__).resolve().parent
NAVIGATION='StudyGuide.html'
GROUP_NAVIGATION='navigation.html'
HEADER='<!doctype html>\n<!-- Generated by regenerate_study_guide.py; navigation v1. -->\n'
SUPPORT_FOLDERS={'assets','cache','caches','__pycache__'}

class Heading(HTMLParser):
    def __init__(self,text):
        super().__init__(convert_charrefs=True);self.active=False;self.done=False;self.parts=[];self.feed(text)
    def handle_starttag(self,tag,attrs):
        if tag=='h1' and not self.done:self.active=True
    def handle_endtag(self,tag):
        if tag=='h1' and self.active:self.active=False;self.done=True
    def handle_data(self,text):
        if self.active:self.parts.append(text)

class SoleChapter(HTMLParser):
    """Accept only an unambiguous, closed chapter list from a guide index."""
    VOID={'area','base','br','col','embed','hr','img','input','link','meta','param','source','track','wbr'}

    def __init__(self,text):
        super().__init__(convert_charrefs=True)
        self.lists=0;self.items=[];self.stack=[];self.current=None
        self.in_link=False;self.invalid=False
        self.feed(text);self.close()

    def handle_starttag(self,tag,attrs):
        values=dict(attrs)
        chapter_list=tag=='ol' and 'lesson-chapters' in (values.get('class') or '').split()
        if chapter_list:self.lists+=1
        if not self.stack:
            if not chapter_list:return
            self.stack=['ol']
        else:
            if tag in {'ol','ul'}:self.invalid=True
            if tag=='li':
                if self.stack!=['ol']:self.invalid=True
                self.current={'hrefs':[],'parts':[]};self.items.append(self.current)
            elif tag=='a':
                if self.current is None or self.in_link:self.invalid=True
                else:self.current['hrefs'].append(values.get('href'))
                self.in_link=True
            if tag not in self.VOID:self.stack.append(tag)
        if len(values)!=len(attrs):self.invalid=True

    def handle_endtag(self,tag):
        if not self.stack:return
        if tag!=self.stack[-1]:
            self.invalid=True
            return
        self.stack.pop()
        if tag=='a':self.in_link=False
        elif tag=='li':self.current=None

    def handle_startendtag(self,tag,attrs):
        self.handle_starttag(tag,attrs)
        if tag not in self.VOID:self.handle_endtag(tag)

    def handle_data(self,value):
        if self.in_link and self.current is not None:self.current['parts'].append(value)


def sole_chapter(index,text):
    chapter=SoleChapter(text)
    if chapter.invalid or chapter.stack or chapter.lists!=1 or len(chapter.items)!=1:return None
    item=chapter.items[0]
    if len(item['hrefs'])!=1:return None
    label=' '.join(''.join(item['parts']).split())
    if not re.fullmatch(r'Objective\s+\d+\s+·\s+\S.*',label):return None
    filename=item['hrefs'][0]
    # No URL syntax, escaped path, directory component or Windows device name.
    if (not isinstance(filename,str) or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]*\.html',filename)
            or filename=='index.html' or PureWindowsPath(filename).is_reserved()):return None
    target=index.parent/filename
    if linked(target) or not target.is_file():return None
    if filename not in {item.name for item in index.parent.iterdir()}:return None
    return label,target

def name_key(name):
    return unicodedata.normalize('NFC',name).casefold()

def natural_key(name):
    """Order embedded decimal numbers numerically, with deterministic text ties."""
    normalized=name_key(name)
    parts=tuple((1,int(part)) if part.isdecimal() else (0,part)
                for part in re.split(r'(\d+)',normalized))
    return parts,normalized,name

def linked(path):
    return path.is_symlink() or getattr(path,'is_junction',lambda:False)()

def safe_path(path, root):
    """Check each component, including missing/dangling link destinations."""
    relative=path.relative_to(root)
    current=root
    for part in ('',*relative.parts):
        current=current/part
        if linked(current):raise ValueError('Refusing a symlink or junction: '+str(current))

def exact_name(directory, name):
    for item in directory.iterdir():
        if name_key(item.name)==name_key(name) and item.name!=name:
            raise ValueError('Filename case/Unicode collision: '+str(item)+'; expected '+name)

def owned(path):
    if linked(path) or not path.is_file():return False
    with path.open('rb') as stream:
        return stream.read(len(HEADER))==HEADER.encode('utf-8')

def href(page, target):
    return quote(Path(os.path.relpath(target,page.parent)).as_posix(),safe='/')

class Folder:
    def __init__(self,path):
        self.path=path
        self.children=[]
        self.guide=None

def guide(folder, index):
    match=re.fullmatch(r'(.+?)(?:-v(\d+))?',folder.name,re.S)
    base=match[1];version=int(match[2]) if match[2] else 1
    objective=re.fullmatch(r'(.+?)-objective-(\d+)',base,re.I)
    lesson=objective[1].replace('_',' ').replace('-',' ') if objective else base.replace('_',' ').replace('-',' ')
    scope='Objective '+str(int(objective[2])) if objective else 'Study guide'
    text=index.read_text(encoding='utf-8')
    heading=' '.join(''.join(Heading(text).parts).split())
    chapter=sole_chapter(index,text)
    return {'folder':folder.name,'group':base.casefold(),'lesson':chapter[0] if chapter else lesson,'scope':scope,
            'version':version,'title':heading or lesson,'target':chapter[1] if chapter else index}

def discover(output, log):
    """One iterative tree scan; supporting trees supply only stale owned pages."""
    tree=Folder(output);nodes=[tree];generated=set()
    pending=[(output,tree)] if output.exists() else []
    while pending:
        directory,node=pending.pop()
        items=sorted(directory.iterdir(),key=lambda p:(name_key(p.name),p.name))
        names={}
        if node is not None:
            for item in items:
                key=name_key(item.name)
                if key in names:
                    raise ValueError('Case/Unicode-colliding filenames: '+str(names[key])+' and '+str(item))
                names[key]=item
        for item in items:
            label=repr(item.relative_to(output).as_posix())
            if linked(item):
                if node is not None:log.append(label+': SKIPPED (symlink or junction)')
                continue
            # Track owned navigation pages for stale-page cleanup.
            if item.name in (NAVIGATION,GROUP_NAVIGATION) and owned(item):generated.add(item)
            if item.is_dir():
                excluded=item.name.startswith('.') or name_key(item.name) in SUPPORT_FOLDERS
                child=Folder(item) if node is not None and not excluded else None
                if child is not None:
                    node.children.append(child);nodes.append(child)
                elif node is not None:log.append(label+': SKIPPED (hidden/supporting folder)')
                # Still find our obsolete pages if a group was moved into an excluded tree.
                pending.append((item,child))
            elif node is not None and directory!=output and item.is_file():
                if item.name=='index.html':
                    node.guide=guide(directory,item)
                    log.append(label+': INCLUDED')
                elif name_key(item.name)=='index.html':
                    log.append(label+': SKIPPED (expected exact filename index.html)')
    # Children were recorded after their parents, including when traversal is deep.
    for node in reversed(nodes):
        node.children=[child for child in node.children if child.guide or child.children]
    return tree,nodes,generated

